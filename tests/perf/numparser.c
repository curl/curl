/*
 * Parse the numbers
 */
static int test_numparser(int argc, const char **argv)
{
  struct curltime start;
  struct curltime end;
  timediff_t us;
  long long hn;
  curl_off_t loops = 500000, loop;
  curl_off_t count = 0;
  curl_off_t ecount = 0; /* errors */
  size_t i;
  size_t nnumbers = CURL_ARRAYSIZE(nums);

  if(argc > 1) {
    const char *ptr = argv[1];
    curl_off_t num;
    if(!curlx_str_number(&ptr, &num, INT_MAX) && !*ptr)
      loops = num;
  }

  curl_mprintf("Found %zu numbers to parse\n", nnumbers);

  start = curlx_now();
  for(loop = 0; loop < loops; loop++) {
    for(i = 0; i < nnumbers; i++) {
      const char *p = nums[i].str;
      curl_off_t val;
      int err;
      if(nums[i].base == 10)
        err = curlx_str_number(&p, &val, nums[i].max);
      else if(nums[i].base == 16)
        err = curlx_str_hex(&p, &val, nums[i].max);
      else
        err = curlx_str_octal(&p, &val, nums[i].max);
      if(err)
        ecount++;
      count++;
    }
  }
  end = curlx_now();
  us = curlx_timediff_us(end, start); /* how many microseconds */
  hn = count ? us * 1000000 / count : 0; /* 1000 times too big */
  curl_mprintf("Numbers:   %" CURL_FORMAT_CURL_OFF_T "\n"
               "Time:      %lld usecs\n"
               "Time/num:  %lld.%03lld ns\n"
               "Nums/sec:  %lld\n"
               "Errors:    %" CURL_FORMAT_CURL_OFF_T "\n",
               count,
               (long long)us,
               (long long)hn / 1000,
               (long long)hn % 1000,
               us ? (long long)(count * 1000000) / us : 0,
               ecount);
  return 0;
}
